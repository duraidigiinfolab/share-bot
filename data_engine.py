def fetch_stock_data(ticker_symbol, period="6mo", interval="1d"):
    """Fetches historical data and calculates technical indicators."""
    print(f"Fetching {period} {interval} data for {ticker_symbol}...")
    try:
        ticker = yf.Ticker(ticker_symbol)
        df = ticker.history(period=period, interval=interval)
        
        if df.empty:
            return None
            
        # Calculate Technical Indicators using pandas_ta
        df.ta.rsi(length=14, append=True)
        df.ta.macd(fast=12, slow=26, signal=9, append=True)
        df.ta.sma(length=20, append=True)
        df.ta.sma(length=50, append=True)
        df.ta.sma(length=200, append=True)
        df.ta.bbands(length=20, std=2, append=True)
        df.ta.atr(length=14, append=True)
        
        # Drop NaN values generated by moving averages
        df = df.dropna()
        
        # Fundamental Data (Only makes sense to pull for daily/long term context)
        fund = {}
        if interval == "1d":
            info = ticker.info
            fund = {
                "trailingPE": info.get("trailingPE", "N/A"),
                "forwardPE": info.get("forwardPE", "N/A"),
                "priceToBook": info.get("priceToBook", "N/A"),
                "debtToEquity": info.get("debtToEquity", "N/A"),
                "trailingEps": info.get("trailingEps", "N/A")
            }
        
        return {
            "symbol": ticker_symbol,
            "df": df,
            "info": fund,
            "interval": interval
        }
    except Exception as e:
        print(f"Error fetching data for {ticker_symbol}: {e}")
        return None

def get_latest_news(ticker_symbol):
    """Fetches recent news titles for the stock using yfinance."""
    try:
        ticker = yf.Ticker(ticker_symbol)
        news = ticker.news
        headlines = [item['title'] for item in news[:5]]
        return headlines
    except:
        return []

def format_data_for_ai(stock_data, headlines):
    """Formats the latest stock data into a concise text block for the AI."""
    df = stock_data['df']
    latest = df.iloc[-1]
    prev = df.iloc[-2]
    
    # Extract latest indicator values
    rsi = round(latest.get('RSI_14', 0), 2)
    macd = round(latest.get('MACD_12_26_9', 0), 2)
    macd_signal = round(latest.get('MACDs_12_26_9', 0), 2)
    sma_20 = round(latest.get('SMA_20', 0), 2)
    sma_50 = round(latest.get('SMA_50', 0), 2)
    sma_200 = round(latest.get('SMA_200', 0), 2)
    atr = round(latest.get('ATRr_14', 0), 2)
    bb_lower = round(latest.get('BBL_20_2.0', 0), 2)
    bb_upper = round(latest.get('BBU_20_2.0', 0), 2)
    
    close_price = round(latest['Close'], 2)
    open_price = round(latest['Open'], 2)
    volume = latest['Volume']
    
    summary = f"""
Stock: {stock_data['symbol']}
Timeframe: {stock_data.get('interval', '1d')}
Day Open Price: {open_price}
Current Price: {close_price}
Previous Price: {round(prev['Close'], 2)}
Volume: {volume}

Technical Indicators:
- Volatility (ATR 14): {atr}
- RSI (14): {rsi}
- MACD (12, 26): {macd} (Signal: {macd_signal})
- Bollinger Bands (20): Lower {bb_lower}, Upper {bb_upper}
- SMA 20: {sma_20}
- SMA 50: {sma_50}
- SMA 200: {sma_200}
"""
    if stock_data.get('info'):
        info = stock_data['info']
        summary += f"""
Fundamental Data:
- Trailing P/E: {info.get('trailingPE')}
- Forward P/E: {info.get('forwardPE')}
- Price to Book: {info.get('priceToBook')}
- Debt to Equity: {info.get('debtToEquity')}
- Trailing EPS: {info.get('trailingEps')}
"""
    
    summary += "\nRecent News Headlines:\n"
    for h in headlines:
        summary += f"- {h}\n"
        
    return summary

